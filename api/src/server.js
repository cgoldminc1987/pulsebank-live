
const express = require('express');
const { Pool } = require('pg');
const redis = require('redis');

const cardsRouter = require('./routes/cards');
const barcodesRouter = require('./routes/barcodes');
const merchantsRouter = require('./routes/merchants');
const distributorRouter = require('./routes/distributor');
const squareRouter = require('./routes/square');
const shopifyRouter = require('./routes/shopify');
const refundsRouter = require('./routes/refunds');
const lithicRouter = require('./routes/lithic');
const kycRouter = require('./routes/kyc');
const stripeRouter = require('./routes/stripe');
const healthRouter = require('./routes/health');

const app = express();
app.use(express.json());
const { join } = require('path');

// CORS: let the merchant terminal call this API from a browser.
const ALLOWED_ORIGINS = (process.env.ALLOWED_ORIGINS || 'https://pulsebank-terminal.onrender.com').split(',').map(s => s.trim()).filter(Boolean);
app.use((req, res, next) => {
  const origin = req.header('Origin');
  if (origin && ALLOWED_ORIGINS.includes(origin)) {
    res.header('Access-Control-Allow-Origin', origin);
    res.header('Vary', 'Origin');
    res.header('Access-Control-Allow-Headers', 'Content-Type, X-Idempotency-Key');
    res.header('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  }
  if (req.method === 'OPTIONS') return res.sendStatus(204);
  next();
});

const pool = new Pool({ connectionString: process.env.DATABASE_URL });
app.locals.pool = pool;

const redisClient = redis.createClient({ url: process.env.REDIS_URL || 'redis://localhost:6379' });
redisClient.connect().catch(console.error);
app.locals.redis = redisClient;

// Idempotency
app.use(async (req,res,next)=>{
  const key = req.header('X-Idempotency-Key');
  if(key && req.method==='POST'){
    req.idemKey = key;
    try {
      if (redisClient.isReady) {
        const cached = await redisClient.get(`idem:${key}`);
        if(cached) return res.status(200).json(JSON.parse(cached));
      }
    } catch(e){ console.warn('idempotency lookup skipped:', e.message); }
  }
  next();
});

app.use('/api/v1', healthRouter);
app.get('/health', (req,res)=> res.redirect('/api/v1/health'));

// Serve an Apple Wallet .pkpass previously generated by POST /api/v1/cards/:id/wallet.
// Issued cards advertise PUBLIC_BASE/wallet/<card>.pkpass - without this route they 404.
const fs = require('fs');
app.get('/wallet/:file', (req,res)=>{
  const file = String(req.params.file || '');
  if (!/^[A-Za-z0-9_-]+\.pkpass$/.test(file)) return res.status(400).json({ error:'invalid wallet file name' });
  const p = `/tmp/${file}`;
  if (!fs.existsSync(p)) return res.status(404).json({ error:'pass not generated yet', how:'POST /api/v1/cards/:id/wallet first', requested:file });
  res.type('application/vnd.apple.pkpass');
  fs.createReadStream(p).pipe(res);
});
app.use('/api/v1/cards', cardsRouter);
app.use('/api/v1/barcodes', barcodesRouter);
app.use('/api/v1/merchants', merchantsRouter);
app.use('/api/v1/distributor', distributorRouter);
app.use('/api/v1/square', squareRouter);
app.use('/api/v1/shopify', shopifyRouter);
app.use('/api/v1/refunds', refundsRouter);
app.use('/api/v1/lithic', lithicRouter);
app.use('/api/v1/kyc', kycRouter);
app.use('/api/v1/stripe', stripeRouter);

// KYC applicant pages (static, no build step)
const kycStatic = express.static(join(__dirname, '..', 'public', 'kyc'), { extensions: ['html'] });
app.use('/kyc', kycStatic);

// 404 as JSON, listing what this host serves
app.use((req,res)=> res.status(404).json({ error:'not found', path:req.path, endpoints:[ 'GET /api/v1/health','POST /api/v1/cards/issue','POST /api/v1/cards/:id/redeem','POST /api/v1/cards/:id/void','GET /api/v1/cards/:id/balance','GET /api/v1/cards/balance/:barcode','POST /api/v1/cards/:id/wallet','POST /api/v1/barcodes/register','DELETE /api/v1/barcodes/:barcode','GET /api/v1/merchants/:id/settlement','POST /api/v1/distributor/issue','POST /api/v1/square/redeem','POST /api/v1/shopify/redeem','POST /api/v1/refunds','GET /api/v1/refunds/:id','POST /api/v1/lithic/cards','GET /api/v1/lithic/status','POST /api/v1/kyc/session','GET /api/v1/kyc/session/:reference','GET /api/v1/kyc/session/:reference/refresh','GET /api/v1/kyc/status','POST /api/v1/stripe/webhook','GET /api/v1/stripe/orders/:sessionId','GET /kyc (applicant page)' ] }));

// BC compliance guard
app.use((err,req,res,next)=>{
  if(err.code==='BC_EXPIRY_NOT_ALLOWED'){
    return res.status(451).json({error:'BC BPCPA: Closed-loop gift cards cannot have expiry', law_ref:'BPCPA s.56'});
  }
  if(err.code==='FINTRAC_KYC_REQUIRED'){
    return res.status(409).json({
      error:err.message,
      fintrac:'MSB + RPAA + identity verification required for reloadable >=$1000',
      kyc_provider:'stripe_identity',
      kyc_start_url:err.kyc_start_url || null,
      kyc_status:err.kyc_status || null
    });
  }
  console.error(err);
  res.status(500).json({error: err.message});
});

const PORT = process.env.PORT || 3000;
if (require.main === module) {
  app.listen(PORT, ()=> console.log(`PulseBank Commands v3 running on ${PORT} - Own host - BC compliant - BINs 469344 Visa / 511340 MC`));
}

module.exports = app;
